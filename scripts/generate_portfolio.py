#!/usr/bin/env python3
"""Generate the portfolio sections of README.md from data/portfolio.json + GitHub.

Two sources feed the generated blocks:

  * Curated   – data/portfolio.json: product families (one entry may group
                several repositories, platforms or services), the archive text
                for public repositories, allowlisted private archive entries and
                the list of repositories that must never appear.
  * Automatic – public repositories owned by OWNER from the public GitHub REST
                API (pagination followed). Repositories claimed by a product
                family are consumed by that family; the rest land in the
                collapsed archive. Forks, disabled/empty repositories, the
                profile repository itself, `profile-hide` topics and every name
                in `profile_excluded_repositories` are skipped.

README.md holds two marker regions that are replaced wholesale:

  <!-- PORTFOLIO:START --> … <!-- PORTFOLIO:END -->   flagships, ecosystem, collaborations
  <!-- ARCHIVE:START -->   … <!-- ARCHIVE:END -->     complete collapsed archive

The proof-strip SVGs (assets/v5/proof-strip-*.svg) are rendered from
data/footprint.json so the numbers shown are exactly the measured ones.

Guarantees: deterministic output for the same input; idempotent (a second run
changes nothing); only the marker regions of README.md are touched; Markdown
is escaped; the only github.com links ever emitted point at listed public
repositories of OWNER; an excluded repository can never reappear; an empty or
failing API response never wipes the existing blocks; the token (if any) is
read from GITHUB_TOKEN and never printed. Standard library only.
"""
