OWNER = "Salihefendihsa"
PROFILE_REPO = OWNER  # the profile README repository has the same name as the owner
API_BASE = "https://api.github.com"
PER_PAGE = 100
TIMEOUT_SECONDS = 20
MAX_PAGES = 20

PORTFOLIO_START = "<!-- PORTFOLIO:START -->"
PORTFOLIO_END = "<!-- PORTFOLIO:END -->"
ARCHIVE_START = "<!-- ARCHIVE:START -->"
ARCHIVE_END = "<!-- ARCHIVE:END -->"
GENERATED_NOTE = "<!-- Generated by scripts/generate_portfolio.py from data/portfolio.json + the public GitHub API. Do not edit by hand. -->"

DEFAULT_PORTFOLIO = os.path.join("data", "portfolio.json")
DEFAULT_FOOTPRINT = os.path.join("data", "footprint.json")
